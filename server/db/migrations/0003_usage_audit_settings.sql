-- 0003: usage / audit / forms / scope-policy / webhooks 落地（DATA_BACKEND=db 第三階段）
-- 與 server/prisma/schema.prisma 對應；經 Supabase 套用（apply_migration）。

-- 每租戶用量聚合計數（單列 upsert；data = TenantUsage）
create table if not exists tenant_usage (
  tenant_id  text primary key,
  data       jsonb not null,
  updated_at timestamptz not null default now()
);

-- 工具稽核流水（append-only；DB 留全史，記憶體只保最近 500 筆供查詢）
create table if not exists audit_logs (
  id        bigint generated by default as identity primary key,
  tenant_id text not null,
  tool_id   text not null,
  user_id   text not null,
  at        timestamptz not null,
  ok        boolean not null,
  summary   text not null,
  error     text
);

create index if not exists audit_logs_tenant_at_idx on audit_logs (tenant_id, at);

-- 租戶自建／覆寫的表單 Definition（每表單一列）
create table if not exists tenant_forms (
  tenant_id  text not null,
  form_id    text not null,
  definition jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (tenant_id, form_id)
);

-- 每租戶授權政策（單列 upsert；data = TenantPolicy）
create table if not exists scope_policies (
  tenant_id  text primary key,
  data       jsonb not null,
  updated_at timestamptz not null default now()
);

-- Webhook 端點（每端點一列；data = WebhookEndpoint 整包）
create table if not exists webhooks (
  id         text primary key,
  tenant_id  text not null,
  data       jsonb not null,
  created_at timestamptz not null
);

create index if not exists webhooks_tenant_idx on webhooks (tenant_id);

-- 同 0001/0002：開 RLS 不建 policy，擋 PostgREST 匿名存取；server 直連不受影響
alter table tenant_usage enable row level security;
alter table audit_logs enable row level security;
alter table tenant_forms enable row level security;
alter table scope_policies enable row level security;
alter table webhooks enable row level security;
