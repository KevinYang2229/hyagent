-- 0021: 知識庫敏感文件存取紀錄（設計：docs/superpowers/specs/2026-11-10-knowledge-access-log-design.md）
-- 經 Supabase SQL Editor 人工套用，必須早於帶此版本的程式部署。
-- 程式先部署時寫入只會失敗並記 log，不影響問答；但存取紀錄會缺漏，所以仍應先套用。
--
-- 只記命中「非公開」（網站訪客看不到）檔案的取用；刻意不存問句、回答與檔案內容——
-- 存了就讓紀錄本身成為需要保護的個資庫。要知道問了什麼，以 ref_id 回查 session。
-- 保存期限：平台預設 KNOWLEDGE_ACCESS_LOG_RETENTION_DAYS（180），租戶可在後台覆寫；每日清除。
create table if not exists knowledge_access_logs (
  id         bigint generated by default as identity primary key,
  tenant_id  text        not null,
  user_id    text        not null,  -- 套用誰的權限（訪客為宿主傳來的 sub，可能為空字串）
  actor_id   text,                  -- admin_test 時為操作的管理者；其他路徑為 NULL
  path       text        not null,  -- chat | table | report | admin_test
  file_id    text,                  -- NULL＝網站來源
  file_name  text        not null,  -- 取用當下的檔名快照（網站來源為網址）
  scopes     text[]      not null,  -- 取用當下的可見性標籤快照
  ref_id     text,                  -- sessionId 等，供交叉追查
  at         timestamptz not null default now()
);

create index if not exists knowledge_access_logs_tenant_at_idx   on knowledge_access_logs (tenant_id, at);
create index if not exists knowledge_access_logs_tenant_file_idx on knowledge_access_logs (tenant_id, file_id, at);
create index if not exists knowledge_access_logs_tenant_user_idx on knowledge_access_logs (tenant_id, user_id, at);
